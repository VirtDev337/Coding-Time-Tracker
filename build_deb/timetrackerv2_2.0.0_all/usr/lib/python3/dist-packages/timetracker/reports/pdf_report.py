"""
Comprehensive, Customizable PDF Report Generator.
Uses ReportLab Platypus to produce professional developer activity reports.
"""

from __future__ import annotations
import os
from datetime import datetime
from pathlib import Path
from typing import Dict, Any, List, Optional

from reportlab.lib import colors
from reportlab.lib.pagesizes import letter
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib.units import inch
from reportlab.platypus import (
    SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle, KeepTogether, Image
)
from reportlab.pdfgen import canvas

from timetracker.config import ReportConfig


class NumberedCanvas(canvas.Canvas):
    """Two-pass canvas to compute total page count and add running headers/footers."""
    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self._saved_page_states = []

    def showPage(self):
        self._saved_page_states.append(dict(self.__dict__))
        self._startPage()

    def save(self):
        num_pages = len(self._saved_page_states)
        for state in self._saved_page_states:
            self.__dict__.update(state)
            self.draw_page_decorations(num_pages)
            super().showPage()
        super().save()

    def draw_page_decorations(self, total_pages: int):
        self.saveState()
        self.setFont("Helvetica", 9)
        self.setFillColor(colors.HexColor("#64748B"))

        # Running header (pages 2 and above)
        if self._pageNumber > 1:
            self.drawString(54, 750, "TimeTracker Developer Activity Report")
            self.drawRightString(612 - 54, 750, datetime.now().strftime("%Y-%m-%d"))
            self.setStrokeColor(colors.HexColor("#E2E8F0"))
            self.setLineWidth(0.75)
            self.line(54, 742, 612 - 54, 742)

        # Running footer (all pages)
        footer_text = f"Page {self._pageNumber} of {total_pages}"
        self.drawRightString(612 - 54, 36, footer_text)
        self.drawString(54, 36, "Generated by TimeTracker v2 • VirtDev")
        self.setStrokeColor(colors.HexColor("#E2E8F0"))
        self.setLineWidth(0.75)
        self.line(54, 48, 612 - 54, 48)
        self.restoreState()


class PDFReportGenerator:
    def __init__(self, output_path: str, config: Optional[ReportConfig] = None):
        self.output_path = output_path
        self.config = config or ReportConfig()
        try:
            self.accent = colors.HexColor(self.config.accent_color)
        except Exception:
            self.accent = colors.HexColor("#1E40AF")
        self.styles = getSampleStyleSheet()
        self._init_styles()

    def _init_styles(self):
        self.styles.add(ParagraphStyle(
            'DocTitle',
            parent=self.styles['Normal'],
            fontName='Helvetica-Bold',
            fontSize=22,
            leading=26,
            textColor=self.accent
        ))
        self.styles.add(ParagraphStyle(
            'DocSubtitle',
            parent=self.styles['Normal'],
            fontName='Helvetica',
            fontSize=10,
            leading=14,
            textColor=colors.HexColor("#64748B"),
            spaceAfter=14
        ))
        self.styles.add(ParagraphStyle(
            'SectionTitle',
            parent=self.styles['Normal'],
            fontName='Helvetica-Bold',
            fontSize=13,
            leading=17,
            textColor=colors.HexColor("#0F172A"),
            spaceBefore=12,
            spaceAfter=6
        ))
        self.styles.add(ParagraphStyle(
            'SubSectionTitle',
            parent=self.styles['Normal'],
            fontName='Helvetica-Bold',
            fontSize=10,
            leading=13,
            textColor=colors.HexColor("#334155"),
            spaceBefore=6,
            spaceAfter=4
        ))
        self.styles.add(ParagraphStyle(
            'KpiNumber',
            parent=self.styles['Normal'],
            fontName='Helvetica-Bold',
            fontSize=16,
            leading=20,
            textColor=self.accent,
            alignment=1  # Centered
        ))
        self.styles.add(ParagraphStyle(
            'KpiLabel',
            parent=self.styles['Normal'],
            fontName='Helvetica-Bold',
            fontSize=8,
            leading=10,
            textColor=colors.HexColor("#64748B"),
            alignment=1  # Centered
        ))
        self.styles.add(ParagraphStyle(
            'Th',
            parent=self.styles['Normal'],
            fontName='Helvetica-Bold',
            fontSize=9,
            leading=11,
            textColor=colors.white
        ))
        self.styles.add(ParagraphStyle(
            'Td',
            parent=self.styles['Normal'],
            fontName='Helvetica',
            fontSize=8.5,
            leading=11,
            textColor=colors.HexColor("#1E293B")
        ))
        self.styles.add(ParagraphStyle(
            'TdRight',
            parent=self.styles['Normal'],
            fontName='Helvetica',
            fontSize=8.5,
            leading=11,
            textColor=colors.HexColor("#1E293B"),
            alignment=2
        ))
        self.styles.add(ParagraphStyle(
            'TdBold',
            parent=self.styles['Normal'],
            fontName='Helvetica-Bold',
            fontSize=8.5,
            leading=11,
            textColor=colors.HexColor("#0F172A")
        ))

    def generate(self, data: Dict[str, Any]) -> str:
        """
        Builds the PDF using aggregated report data from Database.get_report_data.
        """
        doc = SimpleDocTemplate(
            self.output_path,
            pagesize=letter,
            leftMargin=54,
            rightMargin=54,
            topMargin=54,
            bottomMargin=54
        )

        story = []

        # 1. Header with Optional Logo
        header_table_data = []
        header_text = [
            Paragraph("Developer Activity Report", self.styles['DocTitle']),
            Paragraph(
                f"<b>Developer:</b> {self.config.developer_name} &nbsp;&nbsp;|&nbsp;&nbsp; "
                f"<b>Period:</b> {data.get('start_date') or 'Earliest'} — {data.get('end_date') or 'Present'} &nbsp;&nbsp;|&nbsp;&nbsp; "
                f"<b>Generated:</b> {datetime.now().strftime('%Y-%m-%d %H:%M')}",
                self.styles['DocSubtitle']
            )
        ]

        if self.config.logo_path and os.path.isfile(self.config.logo_path):
            try:
                logo_img = Image(self.config.logo_path, width=1.4 * inch, height=0.6 * inch)
                header_table_data = [[header_text, logo_img]]
                header_table = Table(header_table_data, colWidths=[384, 120])
                header_table.setStyle(TableStyle([
                    ('VALIGN', (0, 0), (-1, -1), 'MIDDLE'),
                    ('ALIGN', (1, 0), (1, 0), 'RIGHT'),
                ]))
                story.append(header_table)
            except Exception:
                story.extend(header_text)
        else:
            story.extend(header_text)

        story.append(Spacer(1, 10))

        # 2. Executive KPI Cards
        total_coding = data.get("total_coding_seconds", 0) / 3600.0
        total_collab = data.get("total_collaboration_seconds", 0) / 3600.0
        total_research = data.get("total_research_seconds", 0) / 3600.0
        total_hours = total_coding + total_collab + total_research
        billable_amount = total_hours * self.config.hourly_rate if self.config.hourly_rate > 0 else 0.0

        kpi_cols = [
            [
                Paragraph("TOTAL TIME", self.styles['KpiLabel']),
                Spacer(1, 4),
                Paragraph(f"{total_hours:.1f} hrs", self.styles['KpiNumber']),
                Spacer(1, 2),
                Paragraph(f"({data.get('total_formatted', '0m')})", self.styles['KpiLabel'])
            ],
            [
                Paragraph("CODING (IDE)", self.styles['KpiLabel']),
                Spacer(1, 4),
                Paragraph(f"{total_coding:.1f} hrs", self.styles['KpiNumber']),
                Spacer(1, 2),
                Paragraph(f"({data.get('coding_formatted', '0m')})", self.styles['KpiLabel'])
            ],
            [
                Paragraph("AI COLLAB (ANTIGRAVITY)", self.styles['KpiLabel']),
                Spacer(1, 4),
                Paragraph(f"{total_collab:.1f} hrs", self.styles['KpiNumber']),
                Spacer(1, 2),
                Paragraph(f"({data.get('collaboration_formatted', '0m')})", self.styles['KpiLabel'])
            ],
            [
                Paragraph("RESEARCH (BROWSER)", self.styles['KpiLabel']),
                Spacer(1, 4),
                Paragraph(f"{total_research:.1f} hrs", self.styles['KpiNumber']),
                Spacer(1, 2),
                Paragraph(f"({data.get('research_formatted', '0m')})", self.styles['KpiLabel'])
            ]
        ]
        col_widths = [126, 126, 126, 126]

        if self.config.hourly_rate > 0:
            kpi_cols.append([
                Paragraph(f"EST. VALUE ({self.config.currency})", self.styles['KpiLabel']),
                Spacer(1, 4),
                Paragraph(f"${billable_amount:,.2f}", self.styles['KpiNumber']),
                Spacer(1, 2),
                Paragraph(f"@{self.config.hourly_rate:.0f}/hr", self.styles['KpiLabel'])
            ])
            col_widths = [100, 100, 104, 100, 100]

        kpi_table = Table([kpi_cols], colWidths=col_widths)
        kpi_table.setStyle(TableStyle([
            ('BACKGROUND', (0, 0), (-1, -1), colors.HexColor("#F8FAFC")),
            ('BOX', (0, 0), (-1, -1), 1, colors.HexColor("#CBD5E1")),
            ('INNERGRID', (0, 0), (-1, -1), 0.5, colors.HexColor("#E2E8F0")),
            ('TOPPADDING', (0, 0), (-1, -1), 8),
            ('BOTTOMPADDING', (0, 0), (-1, -1), 8),
            ('ALIGN', (0, 0), (-1, -1), 'CENTER'),
        ]))
        story.append(kpi_table)
        story.append(Spacer(1, 16))

        # 3. Projects Breakdown Table
        story.append(Paragraph("Projects Breakdown", self.styles['SectionTitle']))
        headers = [
            Paragraph("Project", self.styles['Th']),
            Paragraph("Coding", self.styles['Th']),
            Paragraph("AI Collab", self.styles['Th']),
            Paragraph("Research", self.styles['Th']),
            Paragraph("Total", self.styles['Th']),
            Paragraph("Share", self.styles['Th'])
        ]
        rows = [headers]

        for p in data.get("projects", []):
            pct = (p["total_seconds"] / total_hours / 3600.0 * 100.0) if total_hours > 0 else 0.0
            rows.append([
                Paragraph(f"<b>{p['name']}</b>", self.styles['Td']),
                Paragraph(p["coding_formatted"], self.styles['Td']),
                Paragraph(p.get("collaboration_formatted", "0m"), self.styles['Td']),
                Paragraph(p["research_formatted"], self.styles['Td']),
                Paragraph(p["total_formatted"], self.styles['TdBold']),
                Paragraph(f"{pct:.1f}%", self.styles['TdRight']),
            ])

        if len(rows) == 1:
            rows.append([Paragraph("No project activity recorded in this period.", self.styles['Td'])] * 6)

        proj_table = Table(rows, colWidths=[154, 70, 70, 70, 70, 70])
        proj_table.setStyle(TableStyle([
            ('BACKGROUND', (0, 0), (-1, 0), self.accent),
            ('ALIGN', (0, 0), (-1, -1), 'LEFT'),
            ('ROWBACKGROUNDS', (0, 1), (-1, -1), [colors.white, colors.HexColor("#F8FAFC")]),
            ('GRID', (0, 0), (-1, -1), 0.5, colors.HexColor("#E2E8F0")),
            ('TOPPADDING', (0, 0), (-1, -1), 5),
            ('BOTTOMPADDING', (0, 0), (-1, -1), 5),
        ]))
        story.append(proj_table)
        story.append(Spacer(1, 16))

        # 4. Daily Activity Timeline
        timeline = data.get("timeline", [])
        if timeline:
            story.append(Paragraph("Daily Activity Timeline", self.styles['SectionTitle']))
            time_headers = [
                Paragraph("Date", self.styles['Th']),
                Paragraph("Coding Time", self.styles['Th']),
                Paragraph("Research Time", self.styles['Th']),
                Paragraph("Total Time", self.styles['Th'])
            ]
            time_rows = [time_headers]
            for d in timeline:
                c_fmt = f"{d['coding_seconds'] // 3600}h {(d['coding_seconds'] % 3600) // 60}m"
                r_fmt = f"{d['research_seconds'] // 3600}h {(d['research_seconds'] % 3600) // 60}m"
                t_fmt = f"{d['total_seconds'] // 3600}h {(d['total_seconds'] % 3600) // 60}m"
                time_rows.append([
                    Paragraph(d["day"], self.styles['Td']),
                    Paragraph(c_fmt, self.styles['Td']),
                    Paragraph(r_fmt, self.styles['Td']),
                    Paragraph(f"<b>{t_fmt}</b>", self.styles['TdBold']),
                ])

            daily_table = Table(time_rows, colWidths=[154, 116, 116, 118])
            daily_table.setStyle(TableStyle([
                ('BACKGROUND', (0, 0), (-1, 0), colors.HexColor("#334155")),
                ('ROWBACKGROUNDS', (0, 1), (-1, -1), [colors.white, colors.HexColor("#F8FAFC")]),
                ('GRID', (0, 0), (-1, -1), 0.5, colors.HexColor("#E2E8F0")),
                ('TOPPADDING', (0, 0), (-1, -1), 4),
                ('BOTTOMPADDING', (0, 0), (-1, -1), 4),
            ]))
            story.append(daily_table)
            story.append(Spacer(1, 16))

        # 5. Detailed Breakdown per Project (Files & Research)
        if self.config.include_details:
            for p in data.get("projects", []):
                has_files = self.config.include_modified_files and bool(p.get("files"))
                has_research = self.config.include_research and bool(p.get("research_topics"))
                if not has_files and not has_research:
                    continue

                proj_elements = []
                proj_elements.append(Paragraph(f"Detail: {p['name']}", self.styles['SectionTitle']))

                if has_files:
                    proj_elements.append(Paragraph("Top Modified Files", self.styles['SubSectionTitle']))
                    f_headers = [Paragraph("File Path", self.styles['Th']), Paragraph("Modifications", self.styles['Th'])]
                    f_rows = [f_headers]
                    for path_str, mods in p["files"]:
                        f_rows.append([
                            Paragraph(path_str, self.styles['Td']),
                            Paragraph(str(mods), self.styles['TdRight'])
                        ])
                    f_table = Table(f_rows, colWidths=[404, 100])
                    f_table.setStyle(TableStyle([
                        ('BACKGROUND', (0, 0), (-1, 0), colors.HexColor("#475569")),
                        ('ROWBACKGROUNDS', (0, 1), (-1, -1), [colors.white, colors.HexColor("#F8FAFC")]),
                        ('GRID', (0, 0), (-1, -1), 0.5, colors.HexColor("#E2E8F0")),
                        ('TOPPADDING', (0, 0), (-1, -1), 3),
                        ('BOTTOMPADDING', (0, 0), (-1, -1), 3),
                    ]))
                    proj_elements.append(f_table)
                    proj_elements.append(Spacer(1, 8))

                if has_research:
                    proj_elements.append(Paragraph("Browser Research & Technical Domains", self.styles['SubSectionTitle']))
                    r_headers = [Paragraph("Domain / Technical Page", self.styles['Th']), Paragraph("Time Spent", self.styles['Th'])]
                    r_rows = [r_headers]
                    for domain_str, dur_fmt in p["research_topics"]:
                        r_rows.append([
                            Paragraph(domain_str, self.styles['Td']),
                            Paragraph(dur_fmt, self.styles['TdRight'])
                        ])
                    r_table = Table(r_rows, colWidths=[404, 100])
                    r_table.setStyle(TableStyle([
                        ('BACKGROUND', (0, 0), (-1, 0), colors.HexColor("#475569")),
                        ('ROWBACKGROUNDS', (0, 1), (-1, -1), [colors.white, colors.HexColor("#F8FAFC")]),
                        ('GRID', (0, 0), (-1, -1), 0.5, colors.HexColor("#E2E8F0")),
                        ('TOPPADDING', (0, 0), (-1, -1), 3),
                        ('BOTTOMPADDING', (0, 0), (-1, -1), 3),
                    ]))
                    proj_elements.append(r_table)
                    proj_elements.append(Spacer(1, 12))

                story.append(KeepTogether(proj_elements))

        # Build PDF
        doc.build(story, canvasmaker=NumberedCanvas)
        return self.output_path
